public class loop {
    public static void main(String[] args){
        int s=0;
        for(int i=0;i<10;i++){
            System.out.println(i);
            
        }
        //next stage
        
        for(int i=0;i<10;i++){
            s+=i;
        }
        System.out.println("sum of i values"+s);
        
    }
    
}
